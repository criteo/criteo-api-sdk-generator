import org.gradle.api.Project
import org.gradle.api.tasks.Delete
import org.gradle.api.tasks.Copy
import org.openapitools.generator.gradle.plugin.tasks.GenerateTask

class Helper {
    final static String criteoPackage = "criteo.api"
    final static int generatorVersion = 0

    final protected Project project
    final private String technologyStack
    final private String clientOutputDir
    final private String nameSeparator
    final public String language
    final public String temporaryBuildDirArtifacts
    final public String parsedApiName
    final public String criteoService
    final private String apiVersionFromName
    final public String criteoApiVersion
    final protected String clientOutputDirPerVersion
    final public String versionInNamespace
    final protected String specPath
    public String namespaceBase
    final public String artifactVersion
    final private String taskSuffix

    Helper(Project project, String technologyStack, String clientOutputDir, nameSeparator, File swaggerFile){
        this.project = project
        this.technologyStack = technologyStack
        this.clientOutputDir = "${project.rootDir}/${project.rootProject.generatedClientsDirName}/${clientOutputDir}"
        this.nameSeparator = nameSeparator
        language = technologyStack.replaceAll(/[^a-zA-Z]/,"").toLowerCase()
        temporaryBuildDirArtifacts = "${project.projectDir}/build"
        parsedApiName = swaggerFile.getName().replace(".json", "").toLowerCase()
        (criteoService, apiVersionFromName) = parsedApiName.tokenize('_');
        criteoApiVersion = apiVersionFromName.replace('-', '_');
        clientOutputDirPerVersion = clientOutputDir + "/" + parsedApiName;
        versionInNamespace =  computeVersionInNamespace()
        specPath = swaggerFile.path;
        namespaceBase = "${criteoPackage}.${criteoService}.${versionInNamespace}".replace('.', nameSeparator).toString(); // example: criteo\api\marketingsolutions\v2021_10
        artifactVersion = getArtifactVersion()
        taskSuffix = "${this.language}_${parsedApiName}"
    }
    def getArtifactVersion() {
        def isPreviewOrExperimental = criteoApiVersion == 'preview' || criteoApiVersion == 'experimental';
        def artifactVersion = isPreviewOrExperimental ? '0' : criteoApiVersion.replaceAll("_",".").toString()
        artifactVersion += ".${generatorVersion}.${getFormattedDate()}" // example: 2021.01.0.211110 for stable , 0.0.211110 for experimental
        return artifactVersion
    }

    String computeVersionInNamespace() {
        def versionInNamespace =  criteoApiVersion
        if (versionInNamespace.matches("[0-9].*"))
            versionInNamespace= "v" + versionInNamespace
        return versionInNamespace
    }

    static def getFormattedDate() {
        def date = new Date()
        def formattedDate = date.format('yyMMdd')
        return formattedDate
    }

    def registerOpenApiGenerateTask(String generatorName, String configFileFullPath, def configOptions) {
        return project.tasks.register("openApiGenerate_${this.language}_${parsedApiName}", GenerateTask) {
            it.generatorName = generatorName
            configFile = configFileFullPath
            templateDir = "${this.project.projectDir}/resources/templates"
            inputSpec = specPath
            it.outputDir = this.clientOutputDirPerVersion
            removeOperationIdPrefix = true
            generateApiTests = false
            generateModelTests = false
            cleanupOutput = true
            it.configOptions = configOptions + [
                    groupId: 'com.criteo',
                    hideGenerationTimestamp : 'true',
            ]
            additionalProperties = [
                    criteoServiceAsPrefix   : this.criteoService.toString().toUpperCase(),
            ]
        }
    }

    def registerCopyLicenseTask() {
        return this.project.tasks.register("copyLicense_${this.technologyStack}_${parsedApiName}", Copy) {
            group = 'Criteo'
            description = 'Copy the license into the client output folder'

            from "$project.projectDir/../LICENSE"
            into clientOutputDirPerVersion
            rename 'LICENSE', 'LICENSE.txt'
        };
    }

    def registerRemoveUnwantedFilesTasks(Iterable<String> unwantedFiles) {
        return this.project.tasks.register("removeUnwantedFiles_" + this.technologyStack + "_" + parsedApiName, Delete) {
            group = 'Criteo'
            description = 'Remove files generated by openapi-generator that we don\'t want to push'

            delete project.fileTree(clientOutputDirPerVersion) {
                include unwantedFiles
            }
            followSymlinks = true
        }
    }

    def registerCreateConfigTask(String configTemplateFileName, String configDir, String destFileName, String sdkFolder="", String testFolder="") {
        return this.project.tasks.register("createConfig_${taskSuffix}", Copy) {
            from "${this.project.projectDir}/${configTemplateFileName}"
            into configDir
            rename { filename -> destFileName }
            filter { line -> line.replaceAll('%sdkFolder%', sdkFolder).replaceAll('%testFolder%', testFolder) }
        }
    }
}